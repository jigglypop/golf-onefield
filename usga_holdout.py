"""USGA R22-01 자료로 누설 없는 보류 검증.

자료: USGA, "Launch conditions of male and female golfers of different skill levels" (R22-01),
Table 6 (볼스피드·발사각·스핀 평균) / Table 7 (캐리·총거리 평균). 성별 × 클럽(드라이버, 6번 아이언) × 집단 5개.
모든 모형은 이 자료를 보기 전에 투어 평균(PGA)으로 이미 동결했다. 여기서는 다시 맞추지 않는다.

주의
  - 행은 '평균 입력'과 '평균 캐리'다. 캐리는 입력에 비선형이라 평균 입력의 캐리 ≠ 캐리의 평균이고,
    실력이 낮은 집단일수록 빗맞은 샷이 섞여 표준편차가 크다(아래 sd). 그래서 집단별로 나눠 본다.
  - 측정 장비는 연구마다 다르다(스테레오 카메라, TrackMan). 남자 프로 드라이버는 PGA 투어 TrackMan.
  - 드라이버의 스핀비 S ≈ 0.07–0.10 은 훈련 자료(아이언, S ≈ 0.16–0.40) 범위 밖이다.

결과 (2026-10-08). 캐리 RMSE yd: B4 / F3 / Z0
  프로 4행 12.33 / 12.07 / 12.62,  전체 20행 11.60 / 14.68 / 14.42,
  6번 아이언 10행 8.49 / 11.57 / 11.16,  드라이버 10행 14.03 / 17.25 / 17.07
판독 [반례]
  - 독립 자료에서 장 하나(F3, Z0)가 4매개 분리 모형(B4)에 진다.
  - 남자 프로 드라이버(S = 0.067): B4 -0.6, F3 -4.7, Z0 -6.7 yd. 각도 pi/4 잠금은 저스핀에서 C_L = C_D 를
    강제해 항력·양력을 모두 과대하게 만든다. 스핀 -> 0 에서 양력 -> 0 이어야 하므로 잠금은 훈련 범위
    밖에서 깨진다. README 의 'S -> 0 극한' 허점이 독립 자료로 확인됐다.
  - 여자 프로 드라이버는 세 모형 모두 -22~-24 yd. 투어 자료(LPGA 140 mph -> 218 yd)와 견주면
    같은 캐리에 볼스피드가 12 mph 낮아 자료 쪽 불일치로 보인다.
  - 아마추어 집단은 모든 모형이 과대 예측한다(평균 입력의 캐리 > 캐리의 평균, 빗맞은 샷).

python -B usga_holdout.py
"""

from __future__ import annotations

import numpy as np

from fewshot import carry, m_B4, m_F2, m_Z1, rmse
from higgs_engine import Air, to_dimless

# (성별, 클럽, 집단, n, 볼스피드 mph, 발사각 deg, 스핀 rpm, 캐리 yd, 캐리 sd, 총거리 yd)
USGA = [
    ("F", "6i", "Pro", 221, 112.9, 15.1, 5217, 155.5, 12.1, 168.1),
    ("F", "6i", "C1", 108, 102.8, 14.2, 4685, 132.0, 23.4, 149.5),
    ("F", "6i", "C2", 148, 90.5, 15.1, 4096, 106.7, 32.7, 127.2),
    ("F", "6i", "C3", 183, 77.6, 13.7, 3712, 75.1, 29.3, 99.1),
    ("F", "6i", "C4", 237, 71.2, 14.3, 3460, 64.5, 32.5, 88.6),
    ("F", "DR", "Pro", 528, 127.6, 14.3, 2872, 216.7, 13.3, 245.3),
    ("F", "DR", "C1", 364, 122.2, 14.1, 3067, 173.6, 25.4, 202.0),
    ("F", "DR", "C2", 236, 109.6, 13.2, 2784, 135.8, 25.9, 166.8),
    ("F", "DR", "C3", 243, 97.0, 11.3, 2671, 100.1, 29.3, 137.3),
    ("F", "DR", "C4", 296, 86.8, 10.4, 3095, 76.5, 37.5, 112.3),
    ("M", "6i", "Pro", 142, 125.0, 12.8, 6097, 176.4, 18.1, 190.5),
    ("M", "6i", "C1", 1341, 120.2, 12.4, 5171, 164.4, 23.1, 178.5),
    ("M", "6i", "C2", 1010, 112.2, 12.1, 4835, 145.5, 31.5, 161.9),
    ("M", "6i", "C3", 321, 105.9, 12.5, 4354, 129.9, 39.3, 150.5),
    ("M", "6i", "C4", 196, 103.8, 11.7, 4942, 119.2, 47.6, 137.5),
    ("M", "DR", "Pro", 12334, 169.0, 11.1, 2259, 262.2, 66.9, 294.6),
    ("M", "DR", "C1", 433, 143.8, 11.4, 3274, 215.1, 23.4, 233.7),
    ("M", "DR", "C2", 400, 130.6, 10.7, 3313, 183.6, 34.5, 206.3),
    ("M", "DR", "C3", 164, 121.9, 12.2, 3202, 163.3, 33.6, 191.1),
    ("M", "DR", "C4", 101, 125.6, 10.2, 3839, 163.1, 49.7, 185.2),
]
COLS = ["sex", "club", "grp", "n", "mph", "deg", "rpm", "carry", "sd", "total"]

# 투어 PGA 7행으로 동결한 값 (이 파일에서는 맞추지 않는다)
FROZEN = {
    "B4 (4매개)": m_B4([0.2627, 0.1852, 0.3612, 0.1765]),
    "F3 (2매개)": m_F2([0.3881, 0.2714]),
    "Z0 (0매개)": m_Z1([np.pi / 8]),
}


def table():
    return {c: np.array([r[i] for r in USGA]) for i, c in enumerate(COLS)}


def main():
    t = table()
    rows = np.column_stack([t["mph"], t["deg"], t["rpm"], t["carry"]])
    _, _, S0 = to_dimless(Air(), t["mph"], t["deg"], t["rpm"])
    pred = {name: carry(m, rows) for name, m in FROZEN.items()}

    print("행별 캐리 (yd): 실측 ± sd | 예측 (실측과의 차)")
    print(f"{'':12} {'S0':>5} {'실측':>7} {'sd':>5} | " + " | ".join(f"{k:>16}" for k in pred))
    for i in range(len(USGA)):
        lab = f"{t['sex'][i]} {t['club'][i]} {t['grp'][i]}"
        cells = " | ".join(f"{pred[k][i]:7.1f} ({pred[k][i] - t['carry'][i]:+6.1f})" for k in pred)
        print(f"{lab:12} {S0[i]:5.3f} {t['carry'][i]:7.1f} {t['sd'][i]:5.1f} | {cells}")

    groups = {
        "프로 4행": t["grp"] == "Pro",
        "프로+C1 8행": np.isin(t["grp"], ["Pro", "C1"]),
        "전체 20행": np.ones(len(USGA), bool),
        "6번 아이언 10행": t["club"] == "6i",
        "드라이버 10행": t["club"] == "DR",
    }
    print("\nRMSE (yd)")
    print(f"{'':16} " + " ".join(f"{k:>12}" for k in pred))
    for g, m in groups.items():
        print(f"{g:16} " + " ".join(f"{rmse(pred[k][m] - t['carry'][m]):12.2f}" for k in pred))
    # sd 로 나눈 z 점수 (빗맞은 샷이 많은 집단의 가중치를 낮춘다)
    print("\n|z| 평균 (차 / sd)")
    print(f"{'':16} " + " ".join(f"{k:>12}" for k in pred))
    for g, m in groups.items():
        print(f"{g:16} " + " ".join(f"{np.mean(np.abs(pred[k][m] - t['carry'][m]) / t['sd'][m]):12.2f}" for k in pred))


if __name__ == "__main__":
    main()
